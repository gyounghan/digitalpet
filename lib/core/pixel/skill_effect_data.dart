/// 스킬 이름으로 이펙트 프레임 조회 (미등록 스킬은 null)
List<PixelSprite>? skillEffectForSkillName(String skillName) {
  final key = skillNameToEffect[skillName];
  return key == null ? null : skillEffectSprites[key];
}

/// 스킬 이름 → 날아가는 투사체 프레임 (미등록 스킬은 null)
List<PixelSprite>? skillProjectileForSkillName(String skillName) {
  final key = skillNameToEffect[skillName];
  if (key == null) return null;
  return skillProjectileSprites[key] ?? skillEffectSprites[key];
}

/// 스킬 이름 → 착탄 프레임 (미등록 스킬은 null)
List<PixelSprite>? skillImpactForSkillName(String skillName) {
  final key = skillNameToEffect[skillName];
  if (key == null) return null;
  return skillImpactSprites[key] ?? skillEffectSprites[key];
}

