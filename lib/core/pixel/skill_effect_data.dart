/// 아트 문자열 1장 → PixelSprite (행 길이가 다르면 예외 — 테스트에서 검증)
PixelSprite _parseFrame(List<String> rows) {
  final size = rows.length;
  final dark = List<int>.filled(size, 0);
  final body = List<int>.filled(size, 0);
  final accent = List<int>.filled(size, 0);
  for (int y = 0; y < size; y++) {
    final row = rows[y];
    if (row.length != size) {
      throw StateError('스킬 이펙트 아트 행 길이 불일치: y=$y (${row.length} != $size)');
    }
    for (int x = 0; x < size; x++) {
      switch (row[x]) {
        case '#':
          dark[y] |= 1 << x;
        case 'o':
          body[y] |= 1 << x;
        case '+':
          accent[y] |= 1 << x;
      }
    }
  }
  return PixelSprite(size: size, dark: dark, body: body, accent: accent);
}

List<PixelSprite> _parseFrames(List<List<String>> art) =>
    art.map(_parseFrame).toList();

/// 이펙트 키 → 3프레임 (최초 접근 시 1회 파싱)
final Map<String, List<PixelSprite>> skillEffectSprites = {
  'strike': _parseFrames(_strikeArt),
  'slash': _parseFrames(_slashArt),
  'dive': _parseFrames(_diveArt),
  'bind': _parseFrames(_bindArt),
  'roar': _parseFrames(_roarArt),
  'guard': _parseFrames(_guardArt),
};

