/// 스킬 이름으로 이펙트 프레임 조회 (미등록 스킬은 null)
List<PixelSprite>? skillEffectForSkillName(String skillName) {
  final key = skillNameToEffect[skillName];
  return key == null ? null : skillEffectSprites[key];
}

/// 시전자 자신 위에 표시하는 스킬인지 (자기 버프 계열)
bool isSelfSkillEffect(String skillName) =>
    skillName == '방어자세' ||
    skillName == '보름달' ||
    skillName == '여의주' ||
    skillName == '버티기';
